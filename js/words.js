  const WORDS = RAW.map(function (r, i) {
    return { id: i, word: r[0], ipa: r[1], pos: r[2], meaning: r[3] };
  });

  // 避免短期内重复出同一个词
  let recent = [];
  function pick(hard) {
    let pool = WORDS;
    if (hard) {
      const long = WORDS.filter(function (w) { return w.word.length >= 8; });
      if (long.length) pool = long;
    }
    let candidates = pool.filter(function (w) { return recent.indexOf(w.id) === -1; });
    if (!candidates.length) { recent = []; candidates = pool; }
    const w = candidates[Math.floor(Math.random() * candidates.length)];
    recent.push(w.id);
    if (recent.length > 18) recent.shift();
    return w;
  }

  // 生成首字母提示，如 "a _ _ _ _ _ _"
  function hint(word, revealCount) {
    const n = revealCount || 1;
    return word.split("").map(function (ch, i) {
      return i < n ? ch : "_";
    }).join(" ");
  }

